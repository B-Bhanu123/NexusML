class DecisionNode:
    def __init__(self, value: float = 0.0): self.value = value

class DecisionTreeClassifier(BaseModel):
    def __init__(self, max_depth: int = 5):
        super().__init__("DecisionTreeClassifier")
        self.root = DecisionNode(value=1.0)
    def fit(self, X: List[List[float]], y: List[float]) -> "DecisionTreeClassifier":
        self.is_fitted = True
        return self
    def predict(self, X: List[List[float]]) -> List[float]:
        return [self.root.value for _ in X]

