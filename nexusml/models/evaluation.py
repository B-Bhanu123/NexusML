from typing import List, Dict, Any

class EvaluationReport:
    @staticmethod
    def accuracy(y_true: List[float], y_pred: List[float]) -> float:
        if not y_true:
            return 0.0
        correct = sum(1 for t, p in zip(y_true, y_pred) if t == p)
        return correct / len(y_true)

